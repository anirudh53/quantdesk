"""Refreshes config/scan_universe.yaml (the wide market-scan list) from published index constituent lists.
Never typed from memory. Run monthly or after index rebalances:  python -m pipeline.universe_refresh
Sources: S&P 500 - Wikipedia constituents table (secondary, updated by editors on rebalances);
         Nifty 100 - NSE archives CSV (primary).
"""
from __future__ import annotations
import io, pathlib, urllib.request
import pandas as pd
import yaml
from .data import now_utc

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "config" / "scan_universe.yaml"
SP500_URL = "https://en.wikipedia.org/wiki/List_of_S%26P_500_companies"
NIFTY100_URL = "https://archives.nseindia.com/content/indices/ind_nifty100list.csv"

def _get(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (quantdesk research)"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8", "replace")

def sp500() -> list:
    t = pd.read_html(io.StringIO(_get(SP500_URL)), attrs={"id": "constituents"})[0]
    # Yahoo uses '-' where the list uses '.', e.g. BRK.B -> BRK-B
    return [{"name": n, "symbol": s.replace(".", "-"), "sector": sec}
            for s, n, sec in zip(t["Symbol"], t["Security"], t["GICS Sector"])]

def nifty100() -> list:
    t = pd.read_csv(io.StringIO(_get(NIFTY100_URL)))
    return [{"name": n, "symbol": f"{s}.NS", "sector": ind} for n, s, ind in zip(t["Company Name"], t["Symbol"], t["Industry"])]

def main():
    us, ind = sp500(), nifty100()
    if len(us) < 480 or len(ind) < 95:                  # a half-parsed page must not silently shrink the universe
        raise SystemExit(f"constituent lists look incomplete (US {len(us)}, IN {len(ind)}); config not changed")
    doc = {"retrieved": now_utc(),
           "sources": {"US": f"S&P 500, {SP500_URL} (secondary)", "IN": f"Nifty 100, {NIFTY100_URL} (NSE, primary)"},
           "US": us, "IN": ind}
    header = "# Generated by `python -m pipeline.universe_refresh`. Do not edit by hand; edit config/universe.yaml for your watchlist.\n"
    OUT.write_text(header + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=200))
    print(f"wrote {OUT}: US {len(us)}, IN {len(ind)}")

if __name__ == "__main__":
    main()
